// دالة إرسال الذكر
function sendZikr(channel) {
    const randomZikr = azkarList[Math.floor(Math.random() * azkarList.length)];
    
    const embed = new EmbedBuilder()
        .setColor('#2b2d31')
        .setTitle('📖 ذكر واستغفار')
        .setDescription(`**${randomZikr}**`)
        .setFooter({ text: 'لا تنسَ ذكر الله • يُرسل كل 10 دقائق' });

    channel.send({ embeds: [embed] });
}

client.on('ready', () => {
    console.log(`✅ البوت جاهز ويعمل باسم: ${client.user.tag}`);

    const channel = client.channels.cache.get(CHANNEL_ID);

    if (channel) {
        // إرسال أول ذكر فور تشغيل البوت
        sendZikr(channel);

        // إرسال ذكر تلقائي كل 10 دقائق
        setInterval(() => {
            sendZikr(channel);
        }, 10 * 60 * 1000);
    } else {
        console.log('❌ لم يتم العثور على القناة، تأكد من كتابة ID القناة الصحيح!');
    }
});

